'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const listeners = new Map();
const context = { window: {}, document: { readyState: 'loading', addEventListener(name, callback) { listeners.set(name, callback); } }, Math, Number, Array, Object, Map, Set };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '..', 'assets/life/scripts/24-panorama.js'), 'utf8'), context);
const api = context.window.NightPanorama, { project, rotate, multiply } = api.projection;
const camera = { orientation: [0,0,0,1], width: 1600, height: 900, fov: Math.PI / 3 };
const near = (actual, expected, label) => assert(Math.abs(actual - expected) < 1e-10, `${label}: ${actual} != ${expected}`);
const center = project(0,0,camera); near(center[0],.5,'center U'); near(center[1],.5,'center V');
const quarterTurn = [0, Math.sin(Math.PI / 4), 0, Math.cos(Math.PI / 4)];
const right = project(0,0,camera,quarterTurn); near(right[0],.75,'yaw right U'); near(right[1],.5,'yaw right V');
const upward = [-Math.sin(Math.PI / 4),0,0,Math.cos(Math.PI / 4)];
near(project(0,0,camera,upward)[1],0,'look up reaches top of texture');
const leftPixel = project(-1,0,camera), rightPixel = project(1,0,camera);
assert(leftPixel[0] < .5 && rightPixel[0] > .5, 'horizontal projection must remain correctly oriented');
assert(project(0,1,camera)[1] < .5 && project(0,-1,camera)[1] > .5, 'top and bottom must not be flipped');
const wide = project(1,0,{ ...camera, width:3200 }); assert(wide[0] > rightPixel[0], 'viewport aspect must affect angular field');
const double = multiply(quarterTurn,quarterTurn), backward = rotate(double,[0,0,1]); near(backward[2],-1,'composed yaw');
const seam = project(0,0,camera,double); assert(seam[0]>=0 && seam[0]<1,'horizontal seam must wrap');
assert(api.canSeeSky(0,0),'missing assets must not block catalog interaction');
assert.equal(api.getSnapshot().status,'preview','absent imagery must never imply approved rendering');
assert.equal(api.setMode('invalid'),false,'invalid modes must be rejected');
assert.equal(api.setQuality('invalid'),false,'invalid quality must be rejected');
assert.equal(api.setSkyMode('invalid'),false,'invalid sky mode must be rejected');
console.log('Panorama validation passed (projection, orientation, aspect, seam, fallback and input contracts).');
